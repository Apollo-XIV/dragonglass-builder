import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { existsSync, mkdirSync, copyFileSync } from "fs";
import { execSync } from "child_process";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, visit the plugin's github repository
*/
`;

const prod = process.argv[2] === "production";

// In dev, build straight into the test vault so reloading Obsidian picks it up.
const vaultPlugin = "vault/.obsidian/plugins/dragonglass-builder";
const outdir = prod ? "." : vaultPlugin;
if (!prod) {
  mkdirSync(outdir, { recursive: true });
  for (const f of ["manifest.json", "styles.css"]) {
    if (existsSync(f)) copyFileSync(f, `${outdir}/${f}`);
  }
}

// What the settings tab prints as the build it is running. A module rather than a
// `define`, because a watch context fixes its defines when it starts and this has to
// change on every rebuild. `-dirty` says the build has changes the commit doesn't.
const buildInfo = {
  name: "build-info",
  setup(build) {
    build.onResolve({ filter: /^virtual:build-info$/ }, (args) => ({ path: args.path, namespace: "build-info" }));
    build.onLoad({ filter: /.*/, namespace: "build-info" }, () => {
      let commit = "unknown";
      try {
        commit = execSync("git describe --always --dirty --abbrev=8", { encoding: "utf8" }).trim();
      } catch {
        // Not a git checkout; the date still says which build this is.
      }
      return {
        contents: `export const commit = ${JSON.stringify(commit)}; export const builtAt = ${JSON.stringify(new Date().toISOString())};`,
        loader: "js",
      };
    });
  },
};

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
    // The desktop-only filesystem reader requires these lazily, so they must stay
    // external under both spellings.
    ...builtins.map((m) => `node:${m}`),
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: `${outdir}/main.js`,
  minify: prod,
  define: { "process.env.NODE_ENV": prod ? '"production"' : '"development"' },
  plugins: [buildInfo],
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
