/**
 * Inlines content/core into src/generated/core-content.ts so the plugin ships its
 * kind and stat-path definitions with no setup. Run by `npm run dev` and `npm run build`.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const root = "content/core";
const out = "src/generated/core-content.ts";

function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir).sort()) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) files.push(...walk(full));
    else if (entry.endsWith(".json")) files.push(full);
  }
  return files;
}

const manifest = JSON.parse(readFileSync(join(root, "source.json"), "utf8"));
const elements = [];
for (const file of walk(join(root, "content"))) {
  const parsed = JSON.parse(readFileSync(file, "utf8"));
  if (Array.isArray(parsed)) elements.push(...parsed);
  else elements.push(parsed);
}

mkdirSync("src/generated", { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/bundle-content.mjs from content/core. Do not edit.\n` +
    `import type { Element } from "../core/types";\n\n` +
    `export const CORE_SOURCE_ID = ${JSON.stringify(manifest.id)};\n` +
    `export const CORE_SOURCE_NAME = ${JSON.stringify(manifest.name)};\n` +
    `export const CORE_ELEMENTS: Element[] = ${JSON.stringify(elements, null, 2)} as Element[];\n`,
);
console.log(`bundled ${elements.length} core elements into ${out}`);
